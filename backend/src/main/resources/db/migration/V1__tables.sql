    primary key (eventslot_id, raum_id)
);

create table RaumBelegbarkeit
(
    isBelegt boolean not null,
    id       INTEGER generated by default as identity,
    raum_id  INTEGER,
    slot_id  INTEGER,
    version  bigint  not null,
    primary key (id),
    unique (raum_id, slot_id)
);

create table Teilnehmer_EventSlot
