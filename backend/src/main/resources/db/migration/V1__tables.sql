create table EventSlot
(
    id               INTEGER generated by default as identity,
    veranstaltung_id INTEGER not null,
    version          bigint  not null,
    description      varchar(255),
    endTime          varchar(255),
    startTime        varchar(255),
    primary key (id)
);

create table Gebaeude
(
    id           INTEGER generated by default as identity,
    version      bigint       not null,
    hausnummer   varchar(255),
    name         varchar(255) not null unique,
    ort          varchar(255) not null,
    postleitzahl varchar(255) not null,
    strasse      varchar(255) not null,
    typ          varchar(255) not null check ((typ in ('SCHULE', 'KINO', 'SPORTHALLE', 'SAAL', 'EXTERN'))),
    primary key (id)
);

create table Nutzer
(
    is_active                 boolean,
    email_change_token_expiry timestamp(6),
    id                        INTEGER generated by default as identity,
    reset_token_expiry        timestamp(6),
    version                   bigint      not null,
    role                      varchar(31) not null check ((role in ('ADMIN', 'TEILNEHMER', 'REFERENT'))),
    biography                 TEXT,
    email                     varchar(255) unique,
    email_change_token        varchar(255),
    first_name                varchar(255),
    gruppe                    varchar(255),
    job_role                  varchar(255),
    last_name                 varchar(255),
    new_email                 varchar(255),
    organisation              varchar(255),
    password_hash             varchar(255),
    reset_token               varchar(255),
    slogan                    varchar(255),
    primary key (id),
    check (role <> 'ADMIN' or (is_active is not null)),
    check (role <> 'TEILNEHMER' or (is_active is not null)),
    check (role <> 'REFERENT' or (is_active is not null))
);

create table Nutzer_Veranstaltung
(
    nutzer_id        INTEGER not null,
    veranstaltung_id INTEGER not null,
    primary key (nutzer_id, veranstaltung_id)
);

create table Planungsergebnis
(
    timeout          integer      not null,
    id               INTEGER generated by default as identity,
    veranstaltung_id INTEGER      not null unique,
    version          bigint       not null,
    solver           varchar(255) not null,
    jsonErgebnis     oid          not null,
    primary key (id)
);

create table Prioritaet
(
    prio      integer not null,
    id            INTEGER generated by default as identity,
    teilnehmer_id INTEGER,
    vortrag_id    INTEGER,
    primary key (id)
);

create table Protokoll
(
    id         INTEGER generated by default as identity,
    referenzId bigint,
    akteur     varchar(255) not null,
    details    TEXT,
    ereignis   varchar(255) not null,
    kategorie  varchar(255) not null check ((kategorie in
                                             ('LOGIN', 'PLANUNG', 'STAMMDATEN', 'SECURITY', 'SYSTEM', 'VERANSTALTUNG',
                                              'NUTZER', 'VORTRAEGE', 'RAUM', 'GEBAEUDE'))),
    zeitpunkt  varchar(255) not null,
    primary key (id)
);

create table Raum
(
    kapazitaet  integer      not null,
    gebaeude_id INTEGER,
    id          INTEGER generated by default as identity,
    version     bigint       not null,
    etage       varchar(255),
    name        varchar(255) not null,
    primary key (id)
);

create table Raum_EventSlot
